"""Write art\\NOTES\\Blender-Boss-proposed-rows.md: every asset built and judged on the Blender side that has no
QUEUE.md row yet, as ready-to-paste rows. The Blender team may not add rows (BRIEF.md); Claude or Richey does.

  python -m assets.proposed"""
import os, re
from bharness.context import DEFAULT_ART
from bharness.plugins.queue import parse, kind_of
from assets.catalog import ASSETS
from assets.tracker import status_of


def main(art=DEFAULT_ART):
    q = open(os.path.join(art, "QUEUE.md"), encoding="utf-8").read()
    rows = {r["asset"]: r for r in parse(q)[0]}
    nums = [int(r["cells"][0]) for r in rows.values() if r["cells"][0].isdigit()]
    n = max([x for x in nums if x < 99] or [0])
    by = {a["name"]: a for a in ASSETS}
    out = ["# Proposed QUEUE.md rows from Blender Boss", "",
           "Generated by `python -m assets.proposed` (blender-harness). Each asset below is **already built**: it passes the",
           "brief's judge, its .glb export passes the self-check, and the .blend and turntables are saved. The Blender team",
           "may only edit the Status and Notes of existing rows, so these need adding by Claude or Richey. Paste them at the",
           "bottom of QUEUE.md as `TODO` (Blender Boss then claims them and sets them READY) or straight as `READY`.", "",
           "| # | Asset | Kind | Size | Status | Notes |", "|---|---|---|---|---|---|"]
    k = 0
    for a in sorted(ASSETS, key=lambda a: (a["priority"], a["category"], a["name"])):
        if a["name"] in rows:
            continue
        s, blend, frame, _ = status_of(a, art, rows)
        if s != "Judged":
            continue
        k += 1
        out.append("| %d | %s | %s | %s | TODO | %s; built, judged, turntables in promo\\%s |" % (
            n + k, a["name"], (kind_of(a["name"]) or "").lower(), a["tier"] or "-", a["mechanic"].replace("|", "/"), a["name"]))
    p = os.path.join(art, "NOTES", "Blender-Boss-proposed-rows.md")
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("%s: %d proposed rows" % (p, k))


if __name__ == "__main__":
    main()
