def spec_for(a):
    n, tier = a["name"], a["tier"]
    if n in SPECIAL:
        mats, boxes = SPECIAL[n]
    elif n.startswith("Wpn_Shield_"):
        mats, boxes = shield(tier)
    else:
        base = n.split("_")[1]
        if base not in SHAPES:
            return None
        head = TIER.get(tier, "steel")
        mats = (["steel", "gold", head] if base == "Sword" and tier in ("Copper", "Iron") else
                ["grip", "gold", head] if base == "Sword" else ["wood", "grip", head])
        if base == "Sword":
            mats = [head if tier else "steel", "gold" if tier != "Gold" else "purple", "grip"]
            boxes = [[s, c, {0: 2, 1: 1, 2: 0}[m]] for s, c, m in SHAPES[base]()]
        else:
            boxes = SHAPES[base]()
    glow = [2] if tier in GLOW or n in ("Tool_Torch", "Tool_Lantern", "Tool_BlockPlacer", "Wpn_Blaster_Pistol", "Wpn_Blaster_Plasma") else []
    if n == "Tool_Lantern": glow = [1]
    if n.startswith("Wpn_Sword") and tier in GLOW: glow = [0]
    return {"asset": n, "materials": mats, "glow": glow, "parts": [{"name": "", "boxes": boxes}]}

SPECS = [s for s in (spec_for(a) for a in sorted(ASSETS, key=lambda a: a["priority"]) if a["category"] in ("Tools", "Weapons")) if s]
