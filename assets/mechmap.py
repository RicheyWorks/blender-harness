"""Write MECHANICS-MAP.md from assets/catalog.py: mechanic -> assets, biome food webs, recipe links.

  python -m assets.mechmap [--out MECHANICS-MAP.md]"""
import collections, os, re, sys
from assets.catalog import ASSETS, BIOMES

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def links():
    """Item -> assets whose ingredients/drops name it (the recipe graph)."""
    used = collections.defaultdict(list)
    names = {a["name"] for a in ASSETS}
    for a in ASSETS:
        for ref in set(re.findall(r"\b(?:Item|Prop|Mob|Tool)_[A-Za-z0-9_]+", a["drops"])):
            ref = ref.rstrip("_")
            if ref in names and ref != a["name"]:
                used[ref].append(a["name"])
    return used


def render():
    by_cat = collections.OrderedDict()
    for a in ASSETS:
        by_cat.setdefault(a["category"], collections.OrderedDict()).setdefault(a["mechanic"].split(":")[0].split(" (")[0], []).append(a)
    L = ["# Daedalus mechanics-to-assets map", "",
         "Generated by `python -m assets.mechmap` from `assets/catalog.py` (blender-harness). Don't edit by hand.",
         "Every asset follows BLENDER-TEAM-BRIEF.md: 1 m cubes, bottom-centre origin, facing -Y, Kind_Name, flat colours.", "",
         "**%d assets** in %d categories. Status lives in `art\\Blender-Boss-Asset-Tracker.xlsx`." % (len(ASSETS), len(by_cat)), "",
         "| Category | Assets | Mechanics |", "|---|---|---|"]
    for c, m in by_cat.items():
        L.append("| %s | %d | %d |" % (c, sum(len(v) for v in m.values()), len(m)))
    for c, m in by_cat.items():
        L += ["", "## " + c, ""]
        for mech, items in m.items():
            L.append("- **%s** (%d): %s" % (mech, len(items), ", ".join("`%s`" % a["name"] for a in items)))
    L += ["", "## Biomes and food webs", ""]
    for biome, b in BIOMES.items():
        L += ["### " + biome, "",
              "- Plants: trees %s (3 growth stages each); shrubs %s; flowers %s; grasses %s; herbs %s; mushrooms %s; fruit %s" % tuple(
                  ", ".join(b.get(k) or ["-"]) for k in ("trees", "shrubs", "flowers", "grasses", "herbs", "mushrooms", "fruit")),
              "- Food web: plants and insects (%s) feed prey (%s) and birds (%s); predators (%s) eat prey; fish: %s%s" % (
                  ", ".join(b["insects"] or ["-"]), ", ".join(b["prey"]), ", ".join(b["birds"]), ", ".join(b["predators"]),
                  ", ".join(b["fish"] or ["-"]), ("; livestock: " + ", ".join(b["livestock"])) if b.get("livestock") else ""), ""]
    L += ["## Recipe links (item -> what names it as an ingredient or source)", "", "| Item | Linked from |", "|---|---|"]
    for item, srcs in sorted(links().items()):
        L.append("| `%s` | %s |" % (item, ", ".join("`%s`" % s for s in sorted(srcs)[:12]) + (" ..." if len(srcs) > 12 else "")))
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    a = sys.argv[1:]
    out = a[a.index("--out") + 1] if "--out" in a else os.path.join(ROOT, "MECHANICS-MAP.md")
    open(out, "w", encoding="utf-8", newline="\n").write(render())
    print("%s: %d assets, %d linked items" % (out, len(ASSETS), len(links())))
