"""Regenerate art\\Blender-Boss-Asset-Tracker.xlsx from the catalog + what is really on disk and on the board.

  python -m assets.tracker [--out path]
Status, from the evidence (never typed by hand):
  Shipped / READY / DOING / REJECTED / BLOCKED  <- the asset's QUEUE.md row, when it has one
  Judged   <- .blend saved AND turntable frames in promo\\<Asset>\\ (the builder only renders after the judge passes)
  Built    <- .blend saved
  Planned  <- nothing yet"""
import os, sys
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment
from openpyxl.utils import get_column_letter
from openpyxl.formatting.rule import CellIsRule
from bharness.context import DEFAULT_ART
from bharness.plugins.queue import parse, state, kind_of
from bharness.plugins.judge import BUDGET
from assets.catalog import ASSETS

CATS = ["Tools", "Weapons", "Armor", "Stations", "Flora", "Fauna", "Gatherables", "Blocks", "Town", "Vehicles", "Sky", "Other Worlds", "Dragon Warrior"]
COLS = ["Asset name", "Category", "Biome/World", "Mechanic it serves", "Ingredients/drops", "Tier", "Tri budget",
        "Moving parts", "Priority", "Status", "File path", "Turntable path", "Notes"]
COLOR = {"Planned": "D9D9D9", "Built": "FFE699", "Judged": "BDD7EE", "READY": "A9D08E", "Shipped": "548235",
         "DOING": "F4B183", "REJECTED": "FF7C80", "BLOCKED": "C9A0DC"}
DONE = ("Judged", "READY", "Shipped")


def status_of(a, art, rows):
    blend = os.path.join(art, kind_of(a["name"]) or "?", a["name"] + ".blend")
    promo = os.path.join(art, "promo", a["name"])
    frame = os.path.join(promo, "turn_01.png")
    r = rows.get(a["name"])
    s = "Planned"
    if os.path.exists(blend):
        s = "Judged" if os.path.exists(frame) else "Built"
    if r:
        st = state(r["status"])
        s = {"SHIPPED": "Shipped", "READY": "READY", "SHIPPING": "READY", "DOING": "DOING", "REJECTED": "REJECTED",
             "BLOCKED": "BLOCKED", "WAITING": "READY"}.get(st, s)
    return s, (blend if os.path.exists(blend) else ""), (frame if os.path.exists(frame) else ""), (r["status"] if r else "no queue row")


def build(art=DEFAULT_ART, out=None):
    out = out or os.path.join(art, "Blender-Boss-Asset-Tracker.xlsx")
    q = os.path.join(art, "QUEUE.md")
    rows = {r["asset"]: r for r in parse(open(q, encoding="utf-8").read())[0]} if os.path.exists(q) else {}
    wb = Workbook(); summ = wb.active; summ.title = "Summary"
    head = Font(bold=True, color="FFFFFF"); hfill = PatternFill("solid", fgColor="3A3F58")
    counts = {}
    for cat in CATS:
        ws = wb.create_sheet(cat[:31])
        ws.append(COLS)
        for c in ws[1]: c.font, c.fill = head, hfill
        for a in [x for x in ASSETS if x["category"] == cat]:
            s, blend, frame, qs = status_of(a, art, rows)
            counts.setdefault(cat, {}).setdefault(s, 0); counts[cat][s] += 1
            notes = "; ".join(x for x in (a["notes"], "board: " + qs) if x)
            ws.append([a["name"], cat, a["world"], a["mechanic"], a["drops"], a["tier"],
                       BUDGET.get(kind_of(a["name"]) or "", 3000), a["parts"], a["priority"], s, blend, frame, notes])
        n = ws.max_row
        ws.freeze_panes = "A2"; ws.auto_filter.ref = "A1:%s%d" % (get_column_letter(len(COLS)), max(n, 2))
        for st, col in COLOR.items():
            ws.conditional_formatting.add("J2:J%d" % max(n, 2), CellIsRule(operator="equal", formula=['"%s"' % st],
                                          fill=PatternFill("solid", fgColor=col)))
        for i, w in enumerate([26, 12, 22, 36, 26, 10, 10, 30, 8, 10, 60, 60, 40], 1):
            ws.column_dimensions[get_column_letter(i)].width = w
    summ.append(["Category", "Total", "Planned", "Built", "Judged", "READY", "Shipped", "Other", "% done (Judged+)"])
    for c in summ[1]: c.font, c.fill = head, hfill
    for cat in CATS:
        c = counts.get(cat, {}); tot = sum(c.values())
        other = tot - sum(c.get(k, 0) for k in ("Planned", "Built", "Judged", "READY", "Shipped"))
        done = sum(c.get(k, 0) for k in DONE)
        summ.append([cat, tot, c.get("Planned", 0), c.get("Built", 0), c.get("Judged", 0), c.get("READY", 0),
                     c.get("Shipped", 0), other, done / tot if tot else 0])
    last = summ.max_row
    summ.append(["TOTAL"] + ["=SUM(%s2:%s%d)" % (L, L, last) for L in "BCDEFGH"] + ["=IF(B%d=0,0,(E%d+F%d+G%d)/B%d)" % ((last + 1,) * 5)])
    for c in summ[last + 1]: c.font = Font(bold=True)
    for r in range(2, last + 2): summ.cell(r, 9).number_format = "0%"
    summ.freeze_panes = "A2"
    for i, w in enumerate([14, 8, 9, 8, 8, 8, 9, 8, 16], 1): summ.column_dimensions[get_column_letter(i)].width = w
    summ.append([]); summ.append(["Generated by blender-harness (python -m assets.tracker) from assets/catalog.py, the .blend files, promo\\ and QUEUE.md. Don't edit by hand; it is regenerated after each build."])
    wb.save(out)
    return out, counts


if __name__ == "__main__":
    a = sys.argv[1:]
    out, counts = build(out=a[a.index("--out") + 1] if "--out" in a else None)
    tot = sum(sum(c.values()) for c in counts.values()); done = sum(c.get(k, 0) for c in counts.values() for k in DONE)
    print("%s: %d assets, %d judged or further" % (out, tot, done))
